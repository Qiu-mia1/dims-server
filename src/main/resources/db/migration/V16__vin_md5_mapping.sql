--   - 驾驶舱告警：VIN 为空的质量告警可经本表反查补齐
--
-- 字段说明（与 Excel Sheet2 列一一对应）：
--   A vehicle_no          车辆编号（V15 等，Excel 内编号）
--   B model_code          车型代码（835BVP4-15 等）
--   C vin                 车辆识别码 VIN（17 位）
--   D md5                 bag 文件 MD5（32 位 hex）
--   E vehicle_type        动力类型 BEV|REEV
--   F configuration       配置包（OuterBanks|Badlands）
--   G optional_equipment  选装配置（空簧/L2.9/多值逗号分隔，空值存 ''）
--   H vehicle_desc        车辆描述（含动力/配置/出口国家/区域等）
--   I department          部门（PMT5|PAT|VI）
--   J purpose             车辆用途说明
--
-- 主键自增（PG identity，MySQL AUTO_INCREMENT 等价物）；
-- vin 与 md5 各加唯一约束（MD5 唯一可支持去重）。
-- ============================================================

CREATE TABLE vin_md5_mapping (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 主键自增 ID
    vehicle_no         VARCHAR(32)  NOT NULL, -- 车辆编号（V15 等）
    model_code         VARCHAR(64)  NOT NULL, -- 车型代码（835BVP4-15 等）
    vin                VARCHAR(32)  NOT NULL, -- 车辆识别码 VIN（17 位）
    md5                VARCHAR(64)  NOT NULL, -- bag 文件 MD5（32 位 hex）
    vehicle_type       VARCHAR(32),  -- 动力类型 BEV|REEV
    configuration      VARCHAR(64),  -- 配置包 OuterBanks|Badlands
    optional_equipment VARCHAR(255), -- 选装配置（空簧/L2.9 等，多值可含逗号）
    vehicle_desc       VARCHAR(512), -- 车辆描述
    department         VARCHAR(32),  -- 部门 PMT5|PAT|VI
    purpose            VARCHAR(512), -- 车辆用途说明
    created_at         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_vin UNIQUE (vin),
    CONSTRAINT uk_md5 UNIQUE (md5)
);

CREATE INDEX idx_vehicle_no ON vin_md5_mapping (vehicle_no);

