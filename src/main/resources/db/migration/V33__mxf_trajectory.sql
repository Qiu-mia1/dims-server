-- V33: MXF 行驶轨迹明细
-- 每个 MXF 包（= 一段行驶轨迹）解析出的 GPS 轨迹点明细。
-- 数据来源：data.log 各 SECTION JSON 中的 pg / enter_pg / exit_pg / cur_pg 字段（加偏经纬度，"经度,纬度"）。
-- event_name 非空表示该点属于某触发事件（如 AEB / NOP / take_over 等），
-- 为空表示包级轨迹点（随日志时间推进的位置快照），包级点按时间排序即完整轨迹线。

CREATE TABLE mxf_trajectory_point (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    packet_id  VARCHAR(64)  NOT NULL,
    event_name VARCHAR(128),
    section    VARCHAR(128),
    point_type VARCHAR(16)  NOT NULL,          -- pg | enter | exit | cur
    log_ts     TIMESTAMP,                      -- UTC 日志时间
    lon        DOUBLE PRECISION NOT NULL,      -- 加偏经度
    lat        DOUBLE PRECISION NOT NULL,      -- 加偏纬度
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_mxf_traj_point_packet       ON mxf_trajectory_point (packet_id);
CREATE INDEX idx_mxf_traj_point_packet_event ON mxf_trajectory_point (packet_id, event_name);
